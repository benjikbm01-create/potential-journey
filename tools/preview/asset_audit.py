#!/usr/bin/env python3
"""Stage 11 asset audit: counts every model/texture/sound asset and writes the quality registry (docs/ASSET_QUALITY.md).

Classifications (one per asset group, and per creature): acceptable, needs refinement, needs redesign, needs complete
reconstruction, missing, broken, not verified. A classification is only "acceptable" when the asset was actually inspected
(preview renderer and/or in-game screenshot); groups nobody inspected in Stage 11 are recorded as "not verified".
Boss/guardian rows use neutral wording (identities are private).
"""
import json
import os
import sys

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
A = os.path.join(ROOT, "src", "main", "resources", "assets", "underdeep")


def count(path, ext):
    n = 0
    for _, _, fs in os.walk(path):
        n += sum(1 for f in fs if f.endswith(ext))
    return n


def main(ingame_verified=()):
    ingame = set(ingame_verified)
    creatures = sorted(f[:-5] for f in os.listdir(os.path.join(A, "creatures")))
    rig2 = [c for c in creatures if json.load(open(os.path.join(A, "creatures", c + ".json"))).get("rig") == 2]
    tracks = json.load(open(os.path.join(A, "music_tracks.json")))
    rows = [
        ("Creature models (wildlife)", len(creatures), "rebuilt from scratch (Stage 11 anatomy rig)",
         "acceptable — inspected in 4-view previews" + (f"; {len(ingame)} also checked in-game" if ingame else "; in-game check pending")),
        ("Creature textures", count(os.path.join(A, "textures", "entity", "creature"), ".png"), "repainted (structured painter, no noise)",
         "acceptable — inspected in previews"),
        ("Creature animation", len(rig2), "rewritten (two-segment legs, chains, wings, fins, blends)",
         "needs refinement — code-reviewed and built; not watched in motion (screenshots show poses only)"),
        ("Guardian models (private)", count(os.path.join(A, "bosses"), ".json"), "detail pass + structured textures",
         "needs redesign — still too blocky; private previews in docs/private/previews/after/"),
        ("Inhabitant (NPC) appearance", 1, "unchanged in Stage 11", "not verified — redesign recommended (Stage 12)"),
        ("Item textures", count(os.path.join(A, "textures", "item"), ".png"),
         "Stage 11.5 remake: weapons/tools/armour redrawn; dishes, drinks, ingots, gems, jewellery, arrows from archetypes; 222 unique items remastered",
         "acceptable - every batch inspected on contact sheets; remastered unique items keep their old silhouettes (refinement possible)"),
        ("Block textures", count(os.path.join(A, "textures", "block"), ".png"),
         "Stage 11.5 remake: stones, ores, minerals, 8 wood sets, 149 plants redrawn; 210 station/furniture/mechanism blocks rebuilt or remastered",
         "acceptable - contact sheets inspected; terrain checked in game (4 regions, night vision)"),
        ("Vanilla cave stone (bundled pack)", 19, "Stage 11.5: 'Underdeep Caverns' built-in pack", "acceptable - loaded and inspected in game"),
        ("Armour model layers", count(os.path.join(A, "textures", "models", "armor"), ".png"), "Stage 11.5: 13 sets by construction family",
         "not verified in game (no armour worn in the screenshot tours)"),
        ("Block / item models", count(os.path.join(A, "models"), ".json"), "unchanged in Stage 11", "not verified"),
        ("Music tracks", len(tracks), "new: original synthesized soundtrack",
         "acceptable by analysis (decode, loudness, spectra, no gaps; in-game capture continuous with crossfades) — not listened to by a human"),
        ("Sound effects / ambience", 0, "none of our own (vanilla sounds are used)", "missing"),
        ("UI / Handbook / HUD art", 0, "unchanged in Stage 11", "not verified"),
    ]
    out = ["# Asset quality registry (Stage 11)", "",
           "Generated by `tools/preview/asset_audit.py`. Classifications are honest: \"acceptable\" only where the asset was "
           "actually inspected; anything not inspected is \"not verified\". Re-run after asset changes.", "",
           "| Asset group | Count | Stage 11 work | Classification |", "|---|---|---|---|"]
    for r in rows:
        out.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |")
    out += ["", "## Creatures (per species)", "", "| Species | Rig | In-game screenshot |", "|---|---|---|"]
    for c in creatures:
        out.append(f"| {c} | {'Stage 11 anatomy' if c in rig2 else 'legacy'} | {'yes' if c in ingame else 'no'} |")
    out += ["", "## Soundtrack", "", "| Context | Tracks |", "|---|---|"]
    ctx = {}
    for t in tracks:
        ctx[t["context"]] = ctx.get(t["context"], 0) + 1
    for k, v in ctx.items():
        out.append(f"| {k} | {v} |")
    with open(os.path.join(ROOT, "docs", "ASSET_QUALITY.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print(f"registry: {len(rows)} groups, {len(creatures)} creatures ({len(rig2)} rebuilt), {len(tracks)} tracks")


if __name__ == "__main__":
    shots = []
    d = os.path.join(ROOT, "run-client", "screenshots")
    if len(sys.argv) > 1 and sys.argv[1] == "--from-screenshots" and os.path.isdir(d):
        shots = [f.split("_", 3)[3].rsplit("_", 1)[0] for f in os.listdir(d) if f.startswith("tour_zoo_")]
    main(shots)
