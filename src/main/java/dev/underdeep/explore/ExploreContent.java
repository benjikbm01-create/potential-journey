package dev.underdeep.explore;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.underdeep.Underdeep;
import dev.underdeep.world.region.RegionType;
import dev.underdeep.world.terrain.CavernLayer;

import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.EnumSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Stage 9 exploration data ({@code data/underdeep/exploration/content.json}, generated by tools/assets/stage9.py):
 * site families with placement metadata, secret rooms, historical records, artifacts, rumours and encounters.
 * Geometry is authored in Java ({@code explore.design}); every family must have a builder (validated at load).
 */
public final class ExploreContent {
    private ExploreContent() {
    }

    public enum Category { RUIN, LANDMARK, DUNGEON, SECRET }

    public enum Scale {
        MINOR(0), REGIONAL(1), SIGNIFICANT(2), LANDMARK(2), SMALL(1), MEDIUM(2), LARGE(3), EXCEPTIONAL(4);

        public final int rank;

        Scale(int rank) {
            this.rank = rank;
        }
    }

    public record Family(String id, Category category, Scale scale, String name, String desc, Style.Culture culture, Set<RegionType> regions,
                         Set<CavernLayer> layers, int radius, int height, int below, double weight, boolean aquatic, int minSpawn,
                         List<String> secrets, String audio) {
        public boolean anyRegion() {
            return regions.isEmpty();
        }

        public boolean fits(RegionType r) {
            return regions.isEmpty() || regions.contains(r);
        }
    }

    public record SecretDef(String id, String name, String desc) {
    }

    public record Record(String id, String title, String culture, String voice, String text, List<String> regions) {
    }

    public record Artifact(String id, String kind, String rarity, boolean unique, int weight, String desc) {
    }

    public record Rumor(String culture, String kind, String text) {
    }

    public record EncounterDef(String id, Set<RegionType> regions, double weight, int cooldownMinutes, boolean rare, String desc) {
    }

    public static final Map<String, Family> FAMILIES = new LinkedHashMap<>();
    public static final Map<String, SecretDef> SECRETS = new LinkedHashMap<>();
    public static final Map<String, Record> RECORDS = new LinkedHashMap<>();
    public static final Map<String, Artifact> ARTIFACTS = new LinkedHashMap<>();
    public static final List<Rumor> RUMORS = new ArrayList<>();
    public static final Map<String, EncounterDef> ENCOUNTERS = new LinkedHashMap<>();

    public static void load() {
        try (Reader r = new InputStreamReader(ExploreContent.class.getResourceAsStream("/data/underdeep/exploration/content.json"), StandardCharsets.UTF_8)) {
            JsonObject o = JsonParser.parseReader(r).getAsJsonObject();
            for (JsonElement e : o.getAsJsonArray("families")) {
                JsonObject f = e.getAsJsonObject();
                Set<RegionType> regions = EnumSet.noneOf(RegionType.class);
                for (JsonElement x : f.getAsJsonArray("regions")) {
                    RegionType t = RegionType.byId(x.getAsString());
                    if (t != null) {
                        regions.add(t);
                    }
                }
                Set<CavernLayer> layers = EnumSet.noneOf(CavernLayer.class);
                for (JsonElement x : f.getAsJsonArray("layers")) {
                    layers.add(CavernLayer.valueOf(x.getAsString().toUpperCase()));
                }
                List<String> secrets = new ArrayList<>();
                f.getAsJsonArray("secrets").forEach(x -> secrets.add(x.getAsString()));
                Family fam = new Family(f.get("id").getAsString(), Category.valueOf(f.get("category").getAsString().toUpperCase()),
                        Scale.valueOf(f.get("scale").getAsString().toUpperCase()), f.get("name").getAsString(), f.get("desc").getAsString(),
                        Style.Culture.valueOf(f.get("culture").getAsString().toUpperCase()), regions, layers, f.get("radius").getAsInt(),
                        f.get("height").getAsInt(), f.get("below").getAsInt(), f.get("weight").getAsDouble(), f.get("aquatic").getAsBoolean(),
                        f.get("minSpawn").getAsInt(), secrets, f.get("audio").getAsString());
                FAMILIES.put(fam.id(), fam);
            }
            for (JsonElement e : o.getAsJsonArray("secrets")) {
                JsonObject s = e.getAsJsonObject();
                SECRETS.put(s.get("id").getAsString(), new SecretDef(s.get("id").getAsString(), s.get("name").getAsString(), s.get("desc").getAsString()));
            }
            for (JsonElement e : o.getAsJsonArray("records")) {
                JsonObject s = e.getAsJsonObject();
                List<String> regions = new ArrayList<>();
                s.getAsJsonArray("regions").forEach(x -> regions.add(x.getAsString()));
                RECORDS.put(s.get("id").getAsString(), new Record(s.get("id").getAsString(), s.get("title").getAsString(), s.get("culture").getAsString(),
                        s.get("voice").getAsString(), s.get("text").getAsString(), regions));
            }
            for (JsonElement e : o.getAsJsonArray("artifacts")) {
                JsonObject s = e.getAsJsonObject();
                ARTIFACTS.put(s.get("id").getAsString(), new Artifact(s.get("id").getAsString(), s.get("kind").getAsString(), s.get("rarity").getAsString(),
                        s.get("unique").getAsBoolean(), s.get("weight").getAsInt(), s.get("desc").getAsString()));
            }
            for (JsonElement e : o.getAsJsonArray("rumors")) {
                JsonObject s = e.getAsJsonObject();
                RUMORS.add(new Rumor(s.get("culture").getAsString(), s.get("kind").getAsString(), s.get("text").getAsString()));
            }
            for (JsonElement e : o.getAsJsonArray("encounters")) {
                JsonObject s = e.getAsJsonObject();
                Set<RegionType> regions = EnumSet.noneOf(RegionType.class);
                for (JsonElement x : s.getAsJsonArray("regions")) {
                    RegionType t = RegionType.byId(x.getAsString());
                    if (t != null) {
                        regions.add(t);
                    }
                }
                ENCOUNTERS.put(s.get("id").getAsString(), new EncounterDef(s.get("id").getAsString(), regions, s.get("weight").getAsDouble(),
                        s.get("cooldown").getAsInt(), s.get("rare").getAsBoolean(), s.get("desc").getAsString()));
            }
        } catch (Exception e) {
            throw new IllegalStateException("Underdeep: cannot read exploration content", e);
        }
        Underdeep.LOGGER.info("Underdeep exploration: {} site families, {} secret rooms, {} records, {} artifacts, {} encounters",
                FAMILIES.size(), SECRETS.size(), RECORDS.size(), ARTIFACTS.size(), ENCOUNTERS.size());
    }

    public static List<Family> byCategory(Category c) {
        return FAMILIES.values().stream().filter(f -> f.category() == c).toList();
    }

    static JsonArray arr(JsonObject o, String k) {
        return o.has(k) ? o.getAsJsonArray(k) : new JsonArray();
    }
}
