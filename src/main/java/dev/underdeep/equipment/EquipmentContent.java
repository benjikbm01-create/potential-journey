package dev.underdeep.equipment;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.underdeep.Underdeep;
import net.minecraft.entity.attribute.EntityAttribute;
import net.minecraft.entity.attribute.EntityAttributeModifier;
import net.minecraft.registry.Registries;
import net.minecraft.registry.entry.RegistryEntry;
import net.minecraft.util.Identifier;
import org.jetbrains.annotations.Nullable;

import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Stage 8 equipment definitions, loaded from {@code data/underdeep/equipment/content.json} (generated by
 * {@code tools/assets/stage8.py}): materials, weapons, tools, bows, arrows, armour sets, accessories, upgrades,
 * components and utility items. Read at mod init (items are registered from it) on both sides.
 */
public final class EquipmentContent {
    private EquipmentContent() {
    }

    /** An attribute modifier definition: attribute id (e.g. generic.armor), amount, operation, optional scope. */
    public record Attr(String attribute, double amount, EntityAttributeModifier.Operation op, String scope) {
        @Nullable
        public RegistryEntry<EntityAttribute> entry() {
            return Registries.ATTRIBUTE.getEntry(Identifier.ofVanilla(attribute)).map(e -> (RegistryEntry<EntityAttribute>) e).orElse(null);
        }
    }

    public record ToolStats(String level, int durability, float speed, float damage, int enchant, String repair) {
    }

    public record ArmorStats(int[] protection, float toughness, float knockback, int durability, int enchant, String repair,
                             Map<String, Double> protect, List<Attr> attrs, Map<String, List<Attr>> pieceAttrs) {
    }

    public record Material(String id, String name, String special, String role, String ingot, @Nullable ToolStats tool, @Nullable ArmorStats armor) {
    }

    public record Weapon(String id, String family, String material, double damage, double speed, double reach, double knockback, int durability,
                         String special) {
    }

    public record Tool(String id, String kind, String material, String special) {
    }

    public record Bow(String id, int draw, float power, int durability) {
    }

    public record Arrow(String id, double damage, @Nullable String effect, int effectSeconds, int effectAmp, int fire) {
    }

    public record Accessory(String id, String slot, String desc, List<Attr> attrs, Map<String, Double> protect, List<String> flags) {
    }

    public record Upgrade(String id, List<String> applies, String group, String desc, List<Attr> attrs, double durability, Map<String, Double> protect,
                          List<String> flags, String kit) {
    }

    public static final Map<String, Material> MATERIALS = new LinkedHashMap<>();
    public static final List<Weapon> WEAPONS = new ArrayList<>();
    public static final List<Tool> TOOLS = new ArrayList<>();
    public static final List<Bow> BOWS = new ArrayList<>();
    public static final List<Arrow> ARROWS = new ArrayList<>();
    public static final List<String> ARMOR_SETS = new ArrayList<>();
    public static final Map<String, Accessory> ACCESSORIES = new LinkedHashMap<>();
    public static final Map<String, Upgrade> UPGRADES = new LinkedHashMap<>();
    public static final List<String> COMPONENTS = new ArrayList<>();
    public static final Map<String, String> UTILITY = new LinkedHashMap<>();
    public static final Map<String, String> BLOCKS = new LinkedHashMap<>();
    /** Stage 9: exploration artifacts among the weapons and accessories (no recipes; rarity shown; ids from stage9.py). */
    public static final java.util.Set<String> ARTIFACTS = new java.util.LinkedHashSet<>();

    public static synchronized void load() {
        if (!MATERIALS.isEmpty()) {
            return;
        }
        try (Reader r = new InputStreamReader(EquipmentContent.class.getResourceAsStream("/data/underdeep/equipment/content.json"),
                StandardCharsets.UTF_8)) {
            JsonObject root = JsonParser.parseReader(r).getAsJsonObject();
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("materials").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                ToolStats ts = null;
                if (!o.get("tool").isJsonNull()) {
                    JsonObject t = o.getAsJsonObject("tool");
                    ts = new ToolStats(t.get("level").getAsString(), t.get("durability").getAsInt(), t.get("speed").getAsFloat(), t.get("damage").getAsFloat(),
                            t.get("enchant").getAsInt(), t.get("repair").getAsString());
                }
                ArmorStats as = null;
                if (!o.get("armor").isJsonNull()) {
                    JsonObject a = o.getAsJsonObject("armor");
                    JsonArray p = a.getAsJsonArray("protection");
                    Map<String, List<Attr>> pieces = new LinkedHashMap<>();
                    for (Map.Entry<String, JsonElement> pe : a.getAsJsonObject("pieceAttrs").entrySet()) {
                        pieces.put(pe.getKey(), attrs(pe.getValue().getAsJsonArray()));
                    }
                    as = new ArmorStats(new int[]{p.get(0).getAsInt(), p.get(1).getAsInt(), p.get(2).getAsInt(), p.get(3).getAsInt()},
                            a.get("toughness").getAsFloat(), a.get("knockback").getAsFloat(), a.get("durability").getAsInt(), a.get("enchant").getAsInt(),
                            a.get("repair").getAsString(), protect(a.getAsJsonObject("protect")), attrs(a.getAsJsonArray("attrs")), pieces);
                }
                MATERIALS.put(e.getKey(), new Material(e.getKey(), o.get("name").getAsString(), o.get("special").getAsString(), o.get("role").getAsString(),
                        o.get("ingot").getAsString(), ts, as));
            }
            if (root.has("artifacts")) {
                root.getAsJsonArray("artifacts").forEach(x -> ARTIFACTS.add(x.getAsString()));
            }
            for (JsonElement e : root.getAsJsonArray("weapons")) {
                JsonObject o = e.getAsJsonObject();
                WEAPONS.add(new Weapon(o.get("id").getAsString(), o.get("family").getAsString(), o.get("material").getAsString(), o.get("damage").getAsDouble(),
                        o.get("speed").getAsDouble(), o.get("reach").getAsDouble(), o.get("knockback").getAsDouble(), o.get("durability").getAsInt(),
                        o.get("special").getAsString()));
            }
            for (JsonElement e : root.getAsJsonArray("tools")) {
                JsonObject o = e.getAsJsonObject();
                TOOLS.add(new Tool(o.get("id").getAsString(), o.get("kind").getAsString(), o.get("material").getAsString(), o.get("special").getAsString()));
            }
            for (JsonElement e : root.getAsJsonArray("bows")) {
                JsonObject o = e.getAsJsonObject();
                BOWS.add(new Bow(o.get("id").getAsString(), o.get("draw").getAsInt(), o.get("power").getAsFloat(), o.get("durability").getAsInt()));
            }
            for (JsonElement e : root.getAsJsonArray("arrows")) {
                JsonObject o = e.getAsJsonObject();
                JsonElement ef = o.get("effect");
                ARROWS.add(new Arrow(o.get("id").getAsString(), o.get("damage").getAsDouble(), ef.isJsonNull() ? null : ef.getAsJsonArray().get(0).getAsString(),
                        ef.isJsonNull() ? 0 : ef.getAsJsonArray().get(1).getAsInt(), ef.isJsonNull() ? 0 : ef.getAsJsonArray().get(2).getAsInt(),
                        o.get("fire").getAsInt()));
            }
            root.getAsJsonArray("armorSets").forEach(x -> ARMOR_SETS.add(x.getAsString()));
            for (JsonElement e : root.getAsJsonArray("accessories")) {
                JsonObject o = e.getAsJsonObject();
                ACCESSORIES.put(o.get("id").getAsString(), new Accessory(o.get("id").getAsString(), o.get("slot").getAsString(), o.get("desc").getAsString(),
                        attrs(o.getAsJsonArray("attrs")), protect(o.getAsJsonObject("protect")), strings(o.getAsJsonArray("flags"))));
            }
            for (JsonElement e : root.getAsJsonArray("upgrades")) {
                JsonObject o = e.getAsJsonObject();
                UPGRADES.put(o.get("id").getAsString(), new Upgrade(o.get("id").getAsString(), strings(o.getAsJsonArray("applies")), o.get("group").getAsString(),
                        o.get("desc").getAsString(), attrs(o.getAsJsonArray("attrs")), o.get("durability").getAsDouble(), protect(o.getAsJsonObject("protect")),
                        strings(o.getAsJsonArray("flags")), o.get("kit").getAsString()));
            }
            root.getAsJsonArray("components").forEach(x -> COMPONENTS.add(x.getAsString()));
            root.getAsJsonObject("utility").entrySet().forEach(x -> UTILITY.put(x.getKey(), x.getValue().getAsString()));
            root.getAsJsonObject("blocks").entrySet().forEach(x -> BLOCKS.put(x.getKey(), x.getValue().getAsString()));
        } catch (Exception e) {
            Underdeep.LOGGER.error("Equipment: could not load content.json", e);
        }
        Underdeep.LOGGER.info("Equipment: {} materials, {} weapons, {} tools, {} bows, {} armour sets, {} accessories, {} upgrades", MATERIALS.size(),
                WEAPONS.size(), TOOLS.size(), BOWS.size(), ARMOR_SETS.size(), ACCESSORIES.size(), UPGRADES.size());
    }

    static List<String> strings(JsonArray a) {
        List<String> out = new ArrayList<>();
        a.forEach(x -> out.add(x.getAsString()));
        return out;
    }

    static Map<String, Double> protect(JsonObject o) {
        Map<String, Double> m = new LinkedHashMap<>();
        o.entrySet().forEach(e -> m.put(e.getKey(), e.getValue().getAsDouble()));
        return m;
    }

    static List<Attr> attrs(JsonArray a) {
        List<Attr> out = new ArrayList<>();
        for (JsonElement e : a) {
            JsonArray x = e.getAsJsonArray();
            out.add(new Attr(x.get(0).getAsString(), x.get(1).getAsDouble(), switch (x.get(2).getAsString()) {
                case "add_multiplied_base" -> EntityAttributeModifier.Operation.ADD_MULTIPLIED_BASE;
                case "add_multiplied_total" -> EntityAttributeModifier.Operation.ADD_MULTIPLIED_TOTAL;
                default -> EntityAttributeModifier.Operation.ADD_VALUE;
            }, x.size() > 3 ? x.get(3).getAsString() : ""));
        }
        return out;
    }

    public static String hazardKey(String h) {
        return h.toLowerCase(Locale.ROOT);
    }
}
