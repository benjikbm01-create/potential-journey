package dev.underdeep.civ.econ;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.underdeep.Underdeep;
import net.minecraft.component.DataComponentTypes;
import net.minecraft.component.type.FoodComponent;
import net.minecraft.item.Item;
import net.minecraft.item.ItemStack;
import net.minecraft.item.Items;
import net.minecraft.registry.Registries;
import net.minecraft.util.Identifier;
import org.jetbrains.annotations.Nullable;

import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.EnumMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Economic goods (Stage 6): every good is an actual registered item, loaded from
 * {@code data/underdeep/economy/goods.json} (generated by {@code tools/economy/generate_economy.py}). Unknown item
 * ids are skipped with a warning so the economy never depends on items that do not exist. The currency is the
 * emerald (Stage 4); amounts in ledgers are in item units, money in emeralds.
 */
public final class Goods {
    private Goods() {
    }

    /** Regional resource categories (ordinals not persisted; ids are). */
    public enum Category {
        GRAIN, PRODUCE, MEAT, FISH, PREPARED_FOOD, TIMBER, LUMBER, STONE, BUILDING, ORE, METAL, FUEL, FIBER, ANIMAL_PRODUCT, HERB, MEDICINE,
        GEM, DECORATIVE, SPECIALTY, TOOLS, EQUIPMENT, LUXURY;

        public boolean food() {
            return this == GRAIN || this == PRODUCE || this == MEAT || this == FISH || this == PREPARED_FOOD;
        }

        public String id() {
            return name().toLowerCase(java.util.Locale.ROOT);
        }
    }

    /** A tradable good. {@code nutrition} comes from the item's food component (0 for non-food). */
    public record Good(String id, Item item, Category category, double value, int nutrition) {
        public boolean food() {
            return nutrition > 0 && category.food();
        }

        public String name() {
            return dev.underdeep.civ.mind.Preferences.name(id);
        }

        public ItemStack stack(int n) {
            return new ItemStack(item, n);
        }
    }

    private static final Map<String, Good> BY_ID = new LinkedHashMap<>();
    private static final Map<Item, Good> BY_ITEM = new java.util.HashMap<>();
    private static final Map<Category, List<Good>> BY_CAT = new EnumMap<>(Category.class);
    /** The currency item (emerald), set when the registry loads. */
    public static Item currency;

    public static synchronized void load() {
        if (!BY_ID.isEmpty()) {
            return;
        }
        currency = Items.EMERALD;
        for (Category c : Category.values()) {
            BY_CAT.put(c, new ArrayList<>());
        }
        try (Reader r = new InputStreamReader(Goods.class.getResourceAsStream("/data/underdeep/economy/goods.json"), StandardCharsets.UTF_8)) {
            JsonObject root = JsonParser.parseReader(r).getAsJsonObject();
            for (JsonElement e : root.getAsJsonArray("goods")) {
                JsonObject o = e.getAsJsonObject();
                String id = o.get("item").getAsString();
                Item item = Registries.ITEM.get(Identifier.of(id));
                if (item == Items.AIR) {
                    Underdeep.LOGGER.warn("Economy: unknown item {} skipped", id);
                    continue;
                }
                FoodComponent food = item.getComponents().get(DataComponentTypes.FOOD);
                Good g = new Good(id, item, Category.valueOf(o.get("category").getAsString()), o.get("value").getAsDouble(),
                        food == null ? 0 : food.nutrition());
                BY_ID.put(id, g);
                BY_ITEM.put(item, g);
                BY_CAT.get(g.category()).add(g);
            }
        } catch (Exception e) {
            Underdeep.LOGGER.error("Economy: could not load goods", e);
        }
        Underdeep.LOGGER.info("Economy: {} goods in {} categories", BY_ID.size(), Category.values().length);
    }

    @Nullable
    public static Good get(String id) {
        return BY_ID.get(id);
    }

    @Nullable
    public static Good of(Item item) {
        return BY_ITEM.get(item);
    }

    @Nullable
    public static Good of(ItemStack s) {
        return s.isEmpty() ? null : BY_ITEM.get(s.getItem());
    }

    public static List<Good> in(Category c) {
        return BY_CAT.getOrDefault(c, Collections.emptyList());
    }

    public static java.util.Collection<Good> all() {
        return Collections.unmodifiableCollection(BY_ID.values());
    }

    public static int count() {
        return BY_ID.size();
    }
}
