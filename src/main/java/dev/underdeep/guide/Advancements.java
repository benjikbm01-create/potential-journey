package dev.underdeep.guide;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import dev.underdeep.Underdeep;
import dev.underdeep.registry.Reg;
import net.fabricmc.fabric.api.attachment.v1.AttachmentRegistry;
import net.fabricmc.fabric.api.attachment.v1.AttachmentType;
import net.minecraft.advancement.criterion.AbstractCriterion;
import net.minecraft.nbt.NbtCompound;
import net.minecraft.nbt.NbtElement;
import net.minecraft.nbt.NbtList;
import net.minecraft.nbt.NbtString;
import net.minecraft.predicate.entity.EntityPredicate;
import net.minecraft.predicate.entity.LootContextPredicate;
import net.minecraft.registry.Registries;
import net.minecraft.registry.Registry;
import net.minecraft.server.network.ServerPlayerEntity;

import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

/**
 * Stage 8 advancement triggers. Gameplay code reports real, completed actions with {@link #event}; each event is
 * counted per player (total and distinct subjects, persistent, kept on death) and fires the {@code underdeep:event}
 * criterion, whose conditions can require an event name, a subject, a minimum count or a minimum number of distinct
 * subjects. Advancement JSON lives in data/underdeep/advancement (generated by tools/advancements/generate.py).
 */
public final class Advancements {
    private Advancements() {
    }

    /** Per-player event counters. */
    public static final class Stats {
        public final Map<String, Integer> counts = new HashMap<>();
        public final Map<String, Set<String>> subjects = new HashMap<>();
        public boolean migrated;

        public static final Codec<Stats> CODEC = NbtCompound.CODEC.xmap(n -> {
            Stats s = new Stats();
            NbtCompound c = n.getCompound("counts");
            for (String k : c.getKeys()) {
                s.counts.put(k, c.getInt(k));
            }
            NbtCompound sub = n.getCompound("subjects");
            for (String k : sub.getKeys()) {
                Set<String> set = new LinkedHashSet<>();
                sub.getList(k, NbtElement.STRING_TYPE).forEach(e -> set.add(e.asString()));
                s.subjects.put(k, set);
            }
            s.migrated = n.getBoolean("migrated");
            return s;
        }, s -> {
            NbtCompound n = new NbtCompound();
            NbtCompound c = new NbtCompound();
            s.counts.forEach(c::putInt);
            n.put("counts", c);
            NbtCompound sub = new NbtCompound();
            s.subjects.forEach((k, v) -> {
                NbtList l = new NbtList();
                v.forEach(x -> l.add(NbtString.of(x)));
                sub.put(k, l);
            });
            n.put("subjects", sub);
            n.putBoolean("migrated", s.migrated);
            n.putInt("schema", 1);
            return n;
        });
    }

    public static AttachmentType<Stats> STATS;
    public static final EventCriterion EVENT = new EventCriterion();

    public static void init() {
        STATS = AttachmentRegistry.<Stats>builder().persistent(Stats.CODEC).copyOnDeath().initializer(Stats::new).buildAndRegister(Reg.id("progress"));
        Registry.register(Registries.CRITERION, Reg.id("event"), EVENT);
    }

    public static Stats stats(ServerPlayerEntity p) {
        return p.getAttachedOrCreate(STATS);
    }

    /** Reports a completed gameplay action. */
    public static void event(ServerPlayerEntity p, String event, String subject) {
        if (STATS == null || p == null) {
            return;
        }
        Stats s = stats(p);
        int n = s.counts.merge(event, 1, Integer::sum);
        Set<String> subs = s.subjects.computeIfAbsent(event, k -> new LinkedHashSet<>());
        if (subject != null && !subject.isEmpty() && subs.size() < 512) {
            subs.add(subject);
        }
        try {
            EVENT.trigger(p, event, subject == null ? "" : subject, n, subs.size());
        } catch (Exception e) {
            Underdeep.LOGGER.warn("advancement trigger failed for {}", event, e);
        }
    }

    /** Re-checks an event's thresholds without counting (migration, login). */
    public static void recheck(ServerPlayerEntity p, String event) {
        Stats s = stats(p);
        int n = s.counts.getOrDefault(event, 0);
        if (n > 0) {
            Set<String> subs = s.subjects.getOrDefault(event, Set.of());
            for (String sub : subs.isEmpty() ? Set.of("") : subs) {
                EVENT.trigger(p, event, sub, n, subs.size());
            }
        }
    }

    public static final class EventCriterion extends AbstractCriterion<EventCriterion.Conditions> {
        @Override
        public Codec<Conditions> getConditionsCodec() {
            return Conditions.CODEC;
        }

        public void trigger(ServerPlayerEntity player, String event, String subject, int count, int distinct) {
            trigger(player, c -> c.matches(event, subject, count, distinct));
        }

        public record Conditions(Optional<LootContextPredicate> player, String event, Optional<String> subject, int min, int distinct)
                implements AbstractCriterion.Conditions {
            public static final Codec<Conditions> CODEC = RecordCodecBuilder.create(i -> i.group(
                    EntityPredicate.LOOT_CONTEXT_PREDICATE_CODEC.optionalFieldOf("player").forGetter(Conditions::player),
                    Codec.STRING.fieldOf("event").forGetter(Conditions::event),
                    Codec.STRING.optionalFieldOf("subject").forGetter(Conditions::subject),
                    Codec.INT.optionalFieldOf("min", 1).forGetter(Conditions::min),
                    Codec.INT.optionalFieldOf("distinct", 0).forGetter(Conditions::distinct)).apply(i, Conditions::new));

            public boolean matches(String e, String s, int count, int dist) {
                return event.equals(e) && subject.map(x -> x.equals(s)).orElse(true) && count >= min && dist >= distinct;
            }
        }
    }
}
