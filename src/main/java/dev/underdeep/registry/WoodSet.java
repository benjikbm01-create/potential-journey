/**
 * A complete Underdeep wood set: logs, wood, stripped variants, planks, stairs, slab, fence, fence
 * gate, door, trapdoor, button, pressure plate, standing/wall signs and hanging signs, plus the
 * species' leaves and sapling (which grows via the {@code underdeep:tree/<name>} configured feature).
 * Assets, recipes, loot and tags are generated by tools/assets/stage2_assets.py.
 */
public final class WoodSet {
    public static final List<WoodSet> ALL = new ArrayList<>();

    public final String name;
    public final BlockSetType setType;
    public final WoodType woodType;
    public final Block log, strippedLog, wood, strippedWood, planks, stairs, slab, fence, fenceGate, door, trapdoor,
            button, pressurePlate, sign, wallSign, hangingSign, wallHangingSign;
    public Block leaves;
    public Block sapling;
    public Block pottedSapling;

    public WoodSet(String name, MapColor planksColor, MapColor barkColor, boolean burnable) {
        this.name = name;
        ALL.add(this);
        this.setType = BlockSetTypeBuilder.copyOf(BlockSetType.OAK).register(Reg.id(name));
        this.woodType = WoodTypeBuilder.copyOf(WoodType.OAK).register(Reg.id(name), setType);
        AbstractBlock.Settings base = AbstractBlock.Settings.copy(Blocks.OAK_PLANKS).mapColor(planksColor);
        if (!burnable) {
            base = AbstractBlock.Settings.create().mapColor(planksColor).strength(2.0f, 3.0f).sounds(BlockSoundGroup.NETHER_WOOD);
        }
        AbstractBlock.Settings logSettings = AbstractBlock.Settings.copy(burnable ? Blocks.OAK_LOG : Blocks.CRIMSON_STEM)
                .mapColor(s -> s.get(PillarBlock.AXIS) == net.minecraft.util.math.Direction.Axis.Y ? planksColor : barkColor);
        log = Reg.blockItem(name + "_log", new PillarBlock(logSettings));
        strippedLog = Reg.blockItem("stripped_" + name + "_log", new PillarBlock(AbstractBlock.Settings.copy(log).mapColor(planksColor)));
        wood = Reg.blockItem(name + "_wood", new PillarBlock(AbstractBlock.Settings.copy(log).mapColor(barkColor)));
        strippedWood = Reg.blockItem("stripped_" + name + "_wood", new PillarBlock(AbstractBlock.Settings.copy(log).mapColor(planksColor)));
        planks = Reg.blockItem(name + "_planks", new Block(base));
        stairs = Reg.blockItem(name + "_stairs", new StairsBlock(planks.getDefaultState(), AbstractBlock.Settings.copy(planks)));
        slab = Reg.blockItem(name + "_slab", new SlabBlock(AbstractBlock.Settings.copy(planks)));
        fence = Reg.blockItem(name + "_fence", new FenceBlock(AbstractBlock.Settings.copy(planks)));
        fenceGate = Reg.blockItem(name + "_fence_gate", new FenceGateBlock(woodType, AbstractBlock.Settings.copy(planks)));
        door = Reg.cutout(Reg.block(name + "_door", new DoorBlock(setType, AbstractBlock.Settings.copy(Blocks.OAK_DOOR).mapColor(planksColor))));
        Reg.item(name + "_door", new TallBlockItem(door, new Item.Settings()));
        trapdoor = Reg.cutout(Reg.blockItem(name + "_trapdoor", new TrapdoorBlock(setType, AbstractBlock.Settings.copy(Blocks.OAK_TRAPDOOR).mapColor(planksColor))));
        button = Reg.blockItem(name + "_button", new ButtonBlock(setType, 30, AbstractBlock.Settings.copy(Blocks.OAK_BUTTON)));
        pressurePlate = Reg.blockItem(name + "_pressure_plate", new PressurePlateBlock(setType, AbstractBlock.Settings.copy(Blocks.OAK_PRESSURE_PLATE).mapColor(planksColor)));
        sign = Reg.block(name + "_sign", new SignBlock(woodType, AbstractBlock.Settings.copy(Blocks.OAK_SIGN).mapColor(planksColor)));
        wallSign = Reg.block(name + "_wall_sign", new WallSignBlock(woodType, AbstractBlock.Settings.copy(Blocks.OAK_WALL_SIGN).mapColor(planksColor).dropsLike(sign)));
        Reg.item(name + "_sign", new SignItem(new Item.Settings().maxCount(16), sign, wallSign));
        hangingSign = Reg.block(name + "_hanging_sign", new HangingSignBlock(woodType, AbstractBlock.Settings.copy(Blocks.OAK_HANGING_SIGN).mapColor(planksColor)));
        wallHangingSign = Reg.block(name + "_wall_hanging_sign", new WallHangingSignBlock(woodType,
                AbstractBlock.Settings.copy(Blocks.OAK_WALL_HANGING_SIGN).mapColor(planksColor).dropsLike(hangingSign)));
        Reg.item(name + "_hanging_sign", new HangingSignItem(hangingSign, wallHangingSign, new Item.Settings().maxCount(16)));

        BlockEntityType.SIGN.addSupportedBlock(sign);
        BlockEntityType.SIGN.addSupportedBlock(wallSign);
        BlockEntityType.HANGING_SIGN.addSupportedBlock(hangingSign);
        BlockEntityType.HANGING_SIGN.addSupportedBlock(wallHangingSign);

        StrippableBlockRegistry.register(log, strippedLog);
        StrippableBlockRegistry.register(wood, strippedWood);
        if (burnable) {
            FlammableBlockRegistry f = FlammableBlockRegistry.getDefaultInstance();
            for (Block b : new Block[]{log, strippedLog, wood, strippedWood}) {
                f.add(b, 5, 5);
            }
            for (Block b : new Block[]{planks, stairs, slab, fence, fenceGate}) {
                f.add(b, 5, 20);
            }
        }
    }

    /** Leaves for this species (luminance &gt; 0 for glowing foliage). */
    public WoodSet leaves(MapColor color, int luminance) {
        this.leaves = Reg.blockItem(name + "_leaves", leavesBlock(color, luminance));
        Reg.CUTOUT_MIPPED.add(leaves);
        FlammableBlockRegistry.getDefaultInstance().add(leaves, 30, 60);
        return this;
    }

    public WoodSet leaves(Block existing) {
        this.leaves = existing;
        return this;
    }

    public static LeavesBlock leavesBlock(MapColor color, int luminance) {
        AbstractBlock.Settings s = AbstractBlock.Settings.copy(Blocks.OAK_LEAVES).mapColor(color);
        if (luminance > 0) {
            s = s.luminance(st -> luminance);
        }
        return new LeavesBlock(s);
    }

    public WoodSet sapling(String species, TagKey<Block> soil, GrowthRule rule, int minLight) {
        this.sapling = sapling(name, species, soil, rule, minLight);
        this.pottedSapling = potted(name, sapling);
        return this;
    }

    public static Block sapling(String blockName, String species, TagKey<Block> soil, GrowthRule rule, int minLight) {
        RegistryKey<ConfiguredFeature<?, ?>> key = RegistryKey.of(RegistryKeys.CONFIGURED_FEATURE, Reg.id("tree/" + species));
        SaplingGenerator gen = new SaplingGenerator("underdeep_" + species, Optional.empty(), Optional.of(key), Optional.empty());
        Block b = Reg.cutout(Reg.blockItem(blockName + "_sapling", new EcoSaplingBlock(gen, soil, rule, minLight,
                AbstractBlock.Settings.copy(Blocks.OAK_SAPLING))));
        return b;
    }

    public static Block potted(String name, Block plant) {
        return Reg.cutout(Reg.block("potted_" + name + "_sapling", new FlowerPotBlock(plant, AbstractBlock.Settings.copy(Blocks.POTTED_OAK_SAPLING))));
    }
}
