    public static void init() {
        FuelRegistry.INSTANCE.add(EMBERITE, 4800);
        FuelRegistry.INSTANCE.add(AMBER_GLOB, 600);
        FuelRegistry.INSTANCE.add(ModPlants.ROTTING_LOG, 200);
        CompostingChanceRegistry c = CompostingChanceRegistry.INSTANCE;
        for (Item i : new Item[]{DUSKBERRIES, SNOWBERRIES, CLIFFBERRIES, GLOWGRAIN_SEEDS, MIRE_RICE, SUNBEAN, MENDLEAF_SPRIG,
                BOGWORT_LEAF, VOIDROOT_FIBER}) {
            c.add(i, 0.3f);
        }
        for (Item i : new Item[]{HONEYFRUIT, BRIAR_FRUIT, SEA_GRAPES, DUSKROOT, CAVE_TRUFFLE, LAKE_CHESTNUT, EMBERPEPPER,
                FROST_TURNIP, GLOWGRAIN, PUFFCAP, INKCAP, RIMECAP}) {
            c.add(i, 0.65f);
        }
        for (Block b : new Block[]{ModPlants.GLOWFERN, ModPlants.GOLDGRASS, ModPlants.MARSH_FERN, ModPlants.SILVERGRASS,
                ModPlants.ASHGRASS, ModPlants.STATIC_GRASS, ModPlants.SHARDGRASS, ModPlants.GHOSTFERN, ModPlants.STEAMFERN}) {
            c.add(b, 0.3f);
        }
        for (WoodSet w : WoodSet.ALL) {
            if (w.leaves != null) {
                c.add(w.leaves, 0.3f);
            }
            c.add(w.sapling, 0.3f);
        }
    }
