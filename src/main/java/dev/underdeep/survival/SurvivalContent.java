package dev.underdeep.survival;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import dev.underdeep.Underdeep;
import net.minecraft.item.Item;
import net.minecraft.item.ItemStack;
import net.minecraft.item.Items;
import net.minecraft.registry.Registries;
import net.minecraft.util.Identifier;
import org.jetbrains.annotations.Nullable;

import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.EnumMap;
import java.util.EnumSet;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Stage 7 content definitions, loaded from {@code data/underdeep/survival/content.json} (generated by
 * {@code tools/assets/stage7.py}). Item definitions are read at mod init (so the items can be registered); ingredient
 * groups and recipes resolve item ids lazily on first use, after every mod has registered its items. Unknown ids are
 * reported once and the affected recipe is disabled, never crashing the game.
 */
public final class SurvivalContent {
    private SurvivalContent() {
    }

    /** Nutrition groups for the variety bonus (ordinals persisted in the player's survival data: append-only). */
    public enum FoodGroup {
        GRAIN, VEGETABLE, FRUIT, FUNGI, MEAT, FISH, SWEET;

        public String id() {
            return name().toLowerCase(Locale.ROOT);
        }
    }

    /** Workstation kinds (ids persisted in block entities as strings). */
    public enum Station {
        POT("pot", 6, true, false, 4), OVEN("oven", 6, false, true, 4), PREP("prep", 6, false, false, 8), KETTLE("kettle", 4, true, false, 4),
        CROCK("crock", 4, false, false, 4), RACK("rack", 1, false, false, 1), HERBAL("herbal", 6, false, false, 8),
        // Stage 8 equipment stations (ids append-only)
        CRUSH("crush", 2, false, false, 4), ALLOY("alloy", 4, false, true, 4), FORGE("forge", 4, false, true, 4), GEMS("gems", 4, false, false, 4),
        LEATHER("leather", 4, false, false, 4);

        public final String id;
        public final int inputs;
        public final boolean heat, fuel;
        /** Maximum batches made from one load. */
        public final int maxBatch;

        Station(String id, int inputs, boolean heat, boolean fuel, int maxBatch) {
            this.id = id;
            this.inputs = inputs;
            this.heat = heat;
            this.fuel = fuel;
            this.maxBatch = maxBatch;
        }

        public static Station of(String id) {
            for (Station s : values()) {
                if (s.id.equals(id)) {
                    return s;
                }
            }
            throw new IllegalArgumentException(id);
        }
    }

    public record Buff(Identifier effect, int seconds, int amplifier) {
    }

    public record FoodDef(String id, int nutrition, float saturation, Set<FoodGroup> groups, String kind, List<Buff> buffs, int stack) {
        public boolean bowl() {
            return "bowl".equals(kind);
        }

        public boolean drink() {
            return "bottle".equals(kind);
        }
    }

    public record MedicineDef(String id, List<Buff> effects, List<Identifier> cures, int heal, int cooldownSeconds, boolean drink) {
    }

    /** One ingredient requirement: an item id or a group "#name", and a count per batch. */
    public record Ingredient(String key, int count) {
        public boolean group() {
            return key.startsWith("#");
        }
    }

    public record Recipe(String id, Station station, List<Ingredient> ingredients, Identifier result, int count, int seconds,
                         @Nullable Identifier container, boolean basic, String civ) {
        public Item resultItem() {
            return Registries.ITEM.get(result);
        }

        @Nullable
        public Item containerItem() {
            return container == null ? null : Registries.ITEM.get(container);
        }

        public ItemStack output(int batches) {
            return new ItemStack(resultItem(), count * batches);
        }
    }

    public static final Map<String, FoodDef> FOODS = new LinkedHashMap<>();
    public static final Map<String, MedicineDef> MEDICINES = new LinkedHashMap<>();
    public static final List<String> MATERIALS = new ArrayList<>();
    public static final Map<String, Boolean> EFFECTS = new LinkedHashMap<>();
    public static final Map<String, Integer> EFFECT_COLORS = new HashMap<>();
    public static final Map<String, Float> COMPOSTABLE = new LinkedHashMap<>();
    private static final Map<String, List<String>> GROUP_IDS = new LinkedHashMap<>();
    private static final Map<String, List<String>> NUTRITION_IDS = new HashMap<>();
    private static final List<Recipe> RECIPES = new ArrayList<>();
    private static final Map<String, Recipe> RECIPE_BY_ID = new LinkedHashMap<>();
    private static final Map<Station, List<Recipe>> BY_STATION = new EnumMap<>(Station.class);
    private static final Map<String, String> STATION_NAMES = new HashMap<>();
    // resolved lazily
    private static Map<String, Set<Item>> groups;
    private static Map<Item, Set<FoodGroup>> nutrition;
    private static boolean loaded;

    public static synchronized void load() {
        if (loaded) {
            return;
        }
        loaded = true;
        for (Station s : Station.values()) {
            BY_STATION.put(s, new ArrayList<>());
        }
        try (Reader r = new InputStreamReader(SurvivalContent.class.getResourceAsStream("/data/underdeep/survival/content.json"),
                StandardCharsets.UTF_8)) {
            JsonObject root = JsonParser.parseReader(r).getAsJsonObject();
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("groups").entrySet()) {
                List<String> ids = new ArrayList<>();
                e.getValue().getAsJsonArray().forEach(x -> ids.add(x.getAsString()));
                GROUP_IDS.put(e.getKey(), ids);
            }
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("nutrition").entrySet()) {
                List<String> gs = new ArrayList<>();
                e.getValue().getAsJsonArray().forEach(x -> gs.add(x.getAsString()));
                NUTRITION_IDS.put(e.getKey(), gs);
            }
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("foods").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                Set<FoodGroup> gs = EnumSet.noneOf(FoodGroup.class);
                for (String g : o.get("groups").getAsString().split(",")) {
                    if (!g.isBlank()) {
                        gs.add(FoodGroup.valueOf(g.trim()));
                    }
                }
                String path = Identifier.of(e.getKey()).getPath();
                FOODS.put(path, new FoodDef(path, o.get("nutrition").getAsInt(), o.get("saturation").getAsFloat(), gs,
                        o.get("kind").getAsString(), buffs(o.getAsJsonArray("buffs")),
                        o.get("stack").isJsonNull() ? 0 : o.get("stack").getAsInt()));
            }
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("medicines").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                List<Identifier> cures = new ArrayList<>();
                o.getAsJsonArray("cures").forEach(x -> cures.add(Identifier.of(x.getAsString())));
                String path = Identifier.of(e.getKey()).getPath();
                MEDICINES.put(path, new MedicineDef(path, buffs(o.getAsJsonArray("effects")), cures, o.get("heal").getAsInt(),
                        o.get("cooldown").getAsInt(), "drink".equals(o.get("use").getAsString())));
            }
            root.getAsJsonArray("materials").forEach(x -> MATERIALS.add(Identifier.of(x.getAsString()).getPath()));
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("effects").entrySet()) {
                JsonObject o = e.getValue().getAsJsonObject();
                EFFECTS.put(e.getKey(), o.get("beneficial").getAsBoolean());
                EFFECT_COLORS.put(e.getKey(), o.get("color").getAsInt());
            }
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("compostable").entrySet()) {
                COMPOSTABLE.put(e.getKey(), e.getValue().getAsFloat());
            }
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("stations").entrySet()) {
                STATION_NAMES.put(e.getKey(), e.getValue().getAsString());
            }
            readRecipes(root.getAsJsonArray("recipes"));
        } catch (Exception e) {
            Underdeep.LOGGER.error("Survival: could not load content.json", e);
        }
        // Stage 8 processing and equipment recipes share the workstation framework
        try (Reader r = new InputStreamReader(SurvivalContent.class.getResourceAsStream("/data/underdeep/equipment/content.json"),
                StandardCharsets.UTF_8)) {
            JsonObject root = JsonParser.parseReader(r).getAsJsonObject();
            for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("stations").entrySet()) {
                STATION_NAMES.put(e.getKey(), e.getValue().getAsString());
            }
            readRecipes(root.getAsJsonArray("recipes"));
        } catch (Exception e) {
            Underdeep.LOGGER.error("Survival: could not load equipment recipes", e);
        }
        Underdeep.LOGGER.info("Survival: {} foods/drinks, {} medicines, {} materials, {} station recipes", FOODS.size(), MEDICINES.size(),
                MATERIALS.size(), RECIPES.size());
    }

    private static void readRecipes(JsonArray arr) {
        for (JsonElement el : arr) {
            JsonObject o = el.getAsJsonObject();
            List<Ingredient> ins = new ArrayList<>();
            for (JsonElement i : o.getAsJsonArray("ingredients")) {
                JsonArray a = i.getAsJsonArray();
                ins.add(new Ingredient(a.get(0).getAsString(), a.get(1).getAsInt()));
            }
            String cont = o.get("container").getAsString();
            Recipe rec = new Recipe(o.get("id").getAsString(), Station.of(o.get("station").getAsString()), List.copyOf(ins),
                    Identifier.of(o.get("result").getAsString()), o.get("count").getAsInt(), o.get("seconds").getAsInt(),
                    cont.isEmpty() ? null : Identifier.of(cont), o.get("basic").getAsBoolean(), o.get("civ").getAsString());
            RECIPES.add(rec);
            RECIPE_BY_ID.put(rec.id(), rec);
            BY_STATION.get(rec.station()).add(rec);
        }
    }

    private static List<Buff> buffs(JsonArray a) {
        List<Buff> out = new ArrayList<>();
        for (JsonElement e : a) {
            JsonArray b = e.getAsJsonArray();
            out.add(new Buff(Identifier.of(b.get(0).getAsString()), b.get(1).getAsInt(), b.get(2).getAsInt()));
        }
        return List.copyOf(out);
    }

    /** Resolves groups, nutrition and validates recipes (after all items are registered). Returns the problems found. */
    public static synchronized List<String> resolve() {
        List<String> problems = new ArrayList<>();
        if (groups != null) {
            return problems;
        }
        Map<String, Set<Item>> g = new HashMap<>();
        for (Map.Entry<String, List<String>> e : GROUP_IDS.entrySet()) {
            Set<Item> items = new HashSet<>();
            for (String id : e.getValue()) {
                Item it = Registries.ITEM.get(Identifier.of(id));
                if (it == Items.AIR) {
                    problems.add("group " + e.getKey() + ": unknown item " + id);
                } else {
                    items.add(it);
                }
            }
            g.put(e.getKey(), Collections.unmodifiableSet(items));
        }
        Map<Item, Set<FoodGroup>> n = new HashMap<>();
        for (Map.Entry<String, List<String>> e : NUTRITION_IDS.entrySet()) {
            Item it = Registries.ITEM.get(Identifier.of(e.getKey()));
            if (it == Items.AIR) {
                problems.add("nutrition: unknown item " + e.getKey());
                continue;
            }
            Set<FoodGroup> gs = EnumSet.noneOf(FoodGroup.class);
            for (String s : e.getValue()) {
                gs.add(FoodGroup.valueOf(s));
            }
            n.put(it, gs);
        }
        groups = g;
        nutrition = n;
        List<Recipe> bad = new ArrayList<>();
        for (Recipe r : RECIPES) {
            boolean ok = Registries.ITEM.get(r.result()) != Items.AIR && (r.container() == null || r.containerItem() != Items.AIR);
            for (Ingredient i : r.ingredients()) {
                if (i.group() ? !groups.containsKey(i.key().substring(1)) : Registries.ITEM.get(Identifier.of(i.key())) == Items.AIR) {
                    ok = false;
                    problems.add("recipe " + r.id() + ": unknown ingredient " + i.key());
                }
            }
            if (!ok) {
                bad.add(r);
            }
        }
        for (Recipe r : bad) {
            RECIPES.remove(r);
            RECIPE_BY_ID.remove(r.id());
            BY_STATION.get(r.station()).remove(r);
        }
        for (String p : problems) {
            Underdeep.LOGGER.warn("Survival content: {}", p);
        }
        return problems;
    }

    public static boolean matches(Ingredient ing, ItemStack s) {
        if (s.isEmpty()) {
            return false;
        }
        if (ing.group()) {
            resolve();
            Set<Item> set = groups.get(ing.key().substring(1));
            return set != null && set.contains(s.getItem());
        }
        return Registries.ITEM.getId(s.getItem()).toString().equals(ing.key());
    }

    /** Every item an ingredient accepts. */
    public static Set<Item> alternatives(Ingredient ing) {
        resolve();
        if (ing.group()) {
            return groups.getOrDefault(ing.key().substring(1), Set.of());
        }
        Item it = Registries.ITEM.get(Identifier.of(ing.key()));
        return it == Items.AIR ? Set.of() : Set.of(it);
    }

    /** The block item of a station (for audits and the handbook). */
    public static Item stationItem(Station s) {
        return Registries.ITEM.get(Identifier.of("underdeep", STATION_ITEMS.getOrDefault(s.id, s.id)));
    }

    private static final Map<String, String> STATION_ITEMS = Map.ofEntries(Map.entry("pot", "cooking_pot"), Map.entry("oven", "clay_oven"),
            Map.entry("prep", "preparation_table"), Map.entry("kettle", "kettle"), Map.entry("crock", "fermentation_crock"),
            Map.entry("rack", "drying_rack"), Map.entry("herbal", "herbalist_table"), Map.entry("crush", "ore_crusher"),
            Map.entry("alloy", "alloy_furnace"), Map.entry("forge", "forge"), Map.entry("gems", "gem_cutter"), Map.entry("leather", "leatherworker_bench"));

    /** Display name of an ingredient key (group keys shown as "any fruit" etc). */
    public static String ingredientName(Ingredient ing) {
        if (ing.group()) {
            return "any " + ing.key().substring(1).replace('_', ' ').replace("cooked ", "cooked ").replace(" src", "");
        }
        Item it = Registries.ITEM.get(Identifier.of(ing.key()));
        return it.getName().getString();
    }

    public static Set<FoodGroup> groupsOf(Item item) {
        resolve();
        Set<FoodGroup> s = nutrition.get(item);
        return s == null ? Set.of() : s;
    }

    public static List<Recipe> recipes() {
        resolve();
        return Collections.unmodifiableList(RECIPES);
    }

    public static List<Recipe> recipes(Station s) {
        resolve();
        return Collections.unmodifiableList(BY_STATION.get(s));
    }

    @Nullable
    public static Recipe recipe(String id) {
        resolve();
        return RECIPE_BY_ID.get(id);
    }

    public static String stationName(Station s) {
        return STATION_NAMES.getOrDefault(s.id, s.id);
    }

    /** Recipes producing an item (for teaching a recipe by eating its result). */
    public static List<Recipe> producing(Item item) {
        resolve();
        Identifier id = Registries.ITEM.getId(item);
        List<Recipe> out = new ArrayList<>();
        for (Recipe r : RECIPES) {
            if (r.result().equals(id)) {
                out.add(r);
            }
        }
        return out;
    }

    /** Regional recipes of a civilization (taught by its cooks). */
    public static List<Recipe> regional(String civ) {
        resolve();
        List<Recipe> out = new ArrayList<>();
        for (Recipe r : RECIPES) {
            if (r.civ().equals(civ)) {
                out.add(r);
            }
        }
        return out;
    }
}
