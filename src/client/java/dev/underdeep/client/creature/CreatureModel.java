package dev.underdeep.client.creature;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.underdeep.wildlife.UnderdeepCreature;
import net.minecraft.client.model.Dilation;
import net.minecraft.client.model.ModelData;
import net.minecraft.client.model.ModelPart;
import net.minecraft.client.model.ModelPartBuilder;
import net.minecraft.client.model.ModelPartData;
import net.minecraft.client.model.ModelTransform;
import net.minecraft.client.model.TexturedModelData;
import net.minecraft.client.render.entity.model.SinglePartEntityModel;
import net.minecraft.util.math.MathHelper;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

/**
 * Data-driven creature model. Geometry comes from {@code assets/underdeep/creatures/<species>.json}
 * (generated by tools/assets/creatures.py); every part has a role (body, head, jaw, neck, leg, tail,
 * wing, fin, tailfin, segment, antenna, crest, decor). Animation is procedural per role, driven by
 * movement and the creature's synced behaviour state (eating, drinking, sleeping, warning, alert,
 * attacking, playing, sitting), so all species share one animation system yet move differently
 * because their bodies differ (gait, leg count, wings, fins, segments).
 */
public final class CreatureModel extends SinglePartEntityModel<UnderdeepCreature> {
    private final ModelPart root;
    private final List<Part> parts = new ArrayList<>();
    private final String gait;
    private final float legLength;

    private record Part(ModelPart p, String role, float phase, int index, int side) {
    }

    public CreatureModel(ModelPart root, JsonObject spec) {
        this.root = root;
        this.gait = spec.has("gait") ? spec.get("gait").getAsString() : "quad";
        this.legLength = spec.has("legLength") ? spec.get("legLength").getAsFloat() : 6;
        Map<String, ModelPart> byName = new HashMap<>();
        collect(root, "root", spec, byName);
        for (JsonElement e : spec.getAsJsonArray("parts")) {
            JsonObject o = e.getAsJsonObject();
            ModelPart p = byName.get(o.get("name").getAsString());
            if (p != null) {
                parts.add(new Part(p, o.get("role").getAsString(), o.has("phase") ? o.get("phase").getAsFloat() : 0,
                        o.has("index") ? o.get("index").getAsInt() : 0, o.has("side") ? o.get("side").getAsInt() : 0));
            }
        }
    }

    private static void collect(ModelPart node, String name, JsonObject spec, Map<String, ModelPart> out) {
        out.put(name, node);
        for (JsonElement e : spec.getAsJsonArray("parts")) {
            JsonObject o = e.getAsJsonObject();
            if (o.get("parent").getAsString().equals(name) && node.hasChild(o.get("name").getAsString())) {
                collect(node.getChild(o.get("name").getAsString()), o.get("name").getAsString(), spec, out);
            }
        }
    }

    /** Builds the model geometry from the JSON spec. */
    public static TexturedModelData build(JsonObject spec) {
        ModelData data = new ModelData();
        Map<String, ModelPartData> nodes = new HashMap<>();
        nodes.put("root", data.getRoot());
        JsonArray arr = spec.getAsJsonArray("parts");
        // parents are always listed before children
        for (JsonElement e : arr) {
            JsonObject o = e.getAsJsonObject();
            ModelPartBuilder b = ModelPartBuilder.create();
            for (JsonElement be : o.getAsJsonArray("boxes")) {
                JsonObject box = be.getAsJsonObject();
                JsonArray uv = box.getAsJsonArray("uv");
                JsonArray from = box.getAsJsonArray("from");
                JsonArray size = box.getAsJsonArray("size");
                b.uv(uv.get(0).getAsInt(), uv.get(1).getAsInt());
                if (box.has("mirror") && box.get("mirror").getAsBoolean()) {
                    b.mirrored();
                } else {
                    b.mirrored(false);
                }
                b.cuboid(from.get(0).getAsFloat(), from.get(1).getAsFloat(), from.get(2).getAsFloat(),
                        size.get(0).getAsFloat(), size.get(1).getAsFloat(), size.get(2).getAsFloat(),
                        new Dilation(box.has("dilate") ? box.get("dilate").getAsFloat() : 0));
            }
            JsonArray piv = o.getAsJsonArray("pivot");
            JsonArray rot = o.has("rot") ? o.getAsJsonArray("rot") : null;
            ModelTransform t = ModelTransform.of(piv.get(0).getAsFloat(), piv.get(1).getAsFloat(), piv.get(2).getAsFloat(),
                    rot == null ? 0 : rot.get(0).getAsFloat(), rot == null ? 0 : rot.get(1).getAsFloat(), rot == null ? 0 : rot.get(2).getAsFloat());
            ModelPartData parent = nodes.get(o.get("parent").getAsString());
            nodes.put(o.get("name").getAsString(), parent.addChild(o.get("name").getAsString(), b, t));
        }
        JsonArray tex = spec.getAsJsonArray("texture");
        return TexturedModelData.of(data, tex.get(0).getAsInt(), tex.get(1).getAsInt());
    }

    @Override
    public ModelPart getPart() {
        return root;
    }

    @Override
    public void setAngles(UnderdeepCreature e, float limbAngle, float limbDistance, float age, float headYaw, float headPitch) {
        root.traverse().forEach(ModelPart::resetTransform);
        byte state = e.state();
        boolean sleeping = state == UnderdeepCreature.SLEEP || e.isInSittingPose();
        boolean flying = !e.isOnGround() && !e.isTouchingWater() && e.hasNoGravity();
        boolean swimming = e.isTouchingWater();
        float amp = Math.min(1.0f, limbDistance) * (gait.equals("hexa") ? 0.7f : 1.0f);
        float speed = gait.equals("biped") ? 0.55f : gait.equals("hexa") ? 1.2f : 0.66f;
        float breathe = MathHelper.sin(age * 0.08f) * 0.25f;

        if (sleeping) {
            root.pivotY += legLength * 0.7f;
        } else if (state == UnderdeepCreature.PLAY) {
            root.pivotY -= Math.abs(MathHelper.sin(age * 0.6f)) * 2.0f;
        }
        for (Part pt : parts) {
            ModelPart p = pt.p;
            switch (pt.role) {
                case "body" -> {
                    p.pivotY += breathe;
                    if (state == UnderdeepCreature.WARN && gait.equals("quad")) {
                        p.pitch -= 0.15f + MathHelper.sin(age * 0.5f) * 0.05f;
                    }
                    if (swimming && gait.equals("fish")) {
                        p.yaw += MathHelper.sin(age * 0.35f) * 0.12f * (0.4f + amp);
                    }
                }
                case "head" -> {
                    p.yaw += MathHelper.clamp(headYaw, -60, 60) * MathHelper.RADIANS_PER_DEGREE * 0.8f;
                    p.pitch += headPitch * MathHelper.RADIANS_PER_DEGREE * 0.6f;
                    if (state == UnderdeepCreature.EAT || state == UnderdeepCreature.DRINK) {
                        p.pitch += 0.7f + MathHelper.sin(age * 0.6f) * 0.12f;
                    } else if (sleeping) {
                        p.pitch += 0.35f;
                        p.yaw += 0.3f;
                    } else if (state == UnderdeepCreature.WARN || state == UnderdeepCreature.ALERT) {
                        p.pitch -= 0.35f;
                    }
                }
                case "neck" -> {
                    if (state == UnderdeepCreature.EAT || state == UnderdeepCreature.DRINK) {
                        p.pitch += 0.55f;
                    } else if (state == UnderdeepCreature.WARN || state == UnderdeepCreature.ALERT) {
                        p.pitch -= 0.25f;
                    }
                }
                case "jaw" -> {
                    if (state == UnderdeepCreature.ATTACK || state == UnderdeepCreature.WARN || e.isAttacking()) {
                        p.pitch += 0.35f + MathHelper.sin(age * 0.8f) * 0.25f;
                    } else if (state == UnderdeepCreature.EAT) {
                        p.pitch += Math.max(0, MathHelper.sin(age * 0.9f)) * 0.3f;
                    }
                }
                case "leg" -> {
                    if (sleeping) {
                        if (gait.equals("hexa") || gait.equals("crab")) {
                            p.roll += pt.side == 0 ? -0.5f : 0.5f; // legs splay, body rests on the ground
                        } else {
                            p.pitch += pt.index == 0 ? 1.4f : -1.4f; // front legs tuck back, hind legs tuck forward
                        }
                    } else if (swimming && !gait.equals("hexa")) {
                        p.pitch += MathHelper.cos(age * 0.4f + pt.phase * MathHelper.PI) * 0.5f;
                    } else if (flying) {
                        p.pitch += 0.6f;
                    } else {
                        float swing = MathHelper.cos(limbAngle * speed + pt.phase * MathHelper.PI) * 1.2f * amp;
                        if (gait.equals("hexa") || gait.equals("crab")) {
                            p.yaw += swing * 0.5f * (pt.side == 0 ? 1 : -1);
                        } else {
                            p.pitch += swing;
                        }
                    }
                }
                case "arm" -> {
                    p.pitch += MathHelper.cos(limbAngle * speed + pt.phase * MathHelper.PI) * 0.4f * amp;
                    if (state == UnderdeepCreature.ATTACK || e.isAttacking()) {
                        p.pitch -= 0.9f + MathHelper.sin(age * 0.7f) * 0.4f;
                    }
                }
                case "tail" -> {
                    float idx = pt.index + 1;
                    p.yaw += MathHelper.sin(age * 0.12f - idx * 0.5f) * 0.12f + MathHelper.cos(limbAngle * speed) * 0.2f * amp;
                    if (sleeping) {
                        p.yaw += 0.5f;
                    }
                    if (state == UnderdeepCreature.WARN) {
                        p.pitch -= 0.3f;
                        p.yaw += MathHelper.sin(age * 1.2f) * 0.2f;
                    }
                }
                case "segment" -> {
                    float idx = pt.index;
                    p.yaw += MathHelper.sin(age * 0.25f + limbAngle * 0.3f - idx * 0.7f) * (0.18f + 0.25f * amp);
                }
                case "wing" -> {
                    float s = pt.side == 0 ? 1 : -1;
                    if (flying || state == UnderdeepCreature.ALERT && !e.isOnGround()) {
                        p.roll += s * (MathHelper.sin(age * 1.1f) * 0.9f + 0.15f);
                    } else if (!e.isOnGround()) {
                        p.roll += s * 0.25f; // gliding: wings spread
                    } else {
                        p.roll += s * (sleeping ? 1.25f : 1.05f); // folded along the body
                    }
                }
                case "fin" -> {
                    float s = pt.side == 0 ? 1 : -1;
                    p.roll += s * MathHelper.sin(age * 0.5f + pt.phase) * 0.35f;
                }
                case "tailfin" -> p.yaw += MathHelper.sin(age * (swimming ? 0.55f : 0.9f)) * 0.45f;
                case "antenna" -> {
                    p.pitch += MathHelper.sin(age * 0.3f + pt.index) * 0.12f;
                    p.yaw += MathHelper.cos(age * 0.23f + pt.index) * 0.1f;
                }
                case "crest" -> {
                    if (state == UnderdeepCreature.WARN || state == UnderdeepCreature.ALERT) {
                        p.pitch -= 0.4f;
                    }
                }
                case "float" -> {
                    p.pivotY += MathHelper.sin(age * 0.1f + pt.index) * 0.8f;
                    p.pitch += MathHelper.sin(age * 0.15f + pt.index * 0.8f) * 0.15f;
                }
                default -> {
                }
            }
        }
    }
}
