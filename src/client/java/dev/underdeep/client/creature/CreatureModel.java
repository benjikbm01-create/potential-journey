package dev.underdeep.client.creature;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import dev.underdeep.wildlife.UnderdeepCreature;
import net.minecraft.client.model.Dilation;
import net.minecraft.client.model.ModelData;
import net.minecraft.client.model.ModelPart;
import net.minecraft.client.model.ModelPartBuilder;
import net.minecraft.client.model.ModelPartData;
import net.minecraft.client.model.ModelTransform;
import net.minecraft.client.model.TexturedModelData;
import net.minecraft.client.render.entity.model.SinglePartEntityModel;
import net.minecraft.util.math.MathHelper;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.WeakHashMap;

/**
 * Data-driven creature model (Stage 11 rig). Geometry comes from {@code assets/underdeep/creatures/<species>.json}
 * (generated by tools/assets/creatures.py from hand-authored anatomies in creature_designs.py). Every part has a role and
 * animation is procedural per role, driven by movement and the creature's synced behaviour state:
 * <ul>
 *   <li>legs are two-segment (leg_upper swings, leg_lower flexes the knee/hock during the lift phase); hexapods and crabs
 *       scuttle with yaw swings and lift rolls; feet counter-rotate to stay flat;</li>
 *   <li>tails, abdomens, body segments and tentacles are chains whose links lag behind each other (a travelling wave);</li>
 *   <li>wings fold at rest and flap in two hinged sections in flight (the outer section trails the inner one);</li>
 *   <li>ears twitch now and then, heads sway idly and track the look target, jaws chew/gape/pant by state;</li>
 *   <li>state changes (sleep, eat, alert, warn) blend smoothly per entity instead of snapping;</li>
 *   <li>juveniles get a larger head (the renderer shrinks the whole body).</li>
 * </ul>
 * Purely visual: no server timing depends on it.
 */
public final class CreatureModel extends SinglePartEntityModel<UnderdeepCreature> {
    private static final int B_SLEEP = 0, B_EAT = 1, B_ALERT = 2, B_WARN = 3, B_ATTACK = 4, B_FLY = 5, B_SWIM = 6, N_BLEND = 7;

    private final ModelPart root;
    private final List<Part> parts = new ArrayList<>();
    private final String gait;
    private final float legLength;
    private final boolean legacy;
    private final Map<UnderdeepCreature, float[]> blends = new WeakHashMap<>();

    private record Part(ModelPart p, String role, float phase, int index, int side, int chain, float[] unfold) {
    }

    public CreatureModel(ModelPart root, JsonObject spec) {
        this.root = root;
        this.gait = spec.has("gait") ? spec.get("gait").getAsString() : "quad";
        this.legLength = spec.has("legLength") ? spec.get("legLength").getAsFloat() : 6;
        this.legacy = !spec.has("rig");
        Map<String, ModelPart> byName = new HashMap<>();
        collect(root, "root", spec, byName);
        for (JsonElement e : spec.getAsJsonArray("parts")) {
            JsonObject o = e.getAsJsonObject();
            ModelPart p = byName.get(o.get("name").getAsString());
            if (p != null) {
                parts.add(new Part(p, o.get("role").getAsString(), o.has("phase") ? o.get("phase").getAsFloat() : 0,
                        o.has("index") ? o.get("index").getAsInt() : 0, o.has("side") ? o.get("side").getAsInt() : 0,
                        o.has("chain") ? o.get("chain").getAsInt() : (o.has("index") ? o.get("index").getAsInt() : 0), unfold(o)));
            }
        }
    }

    private static float[] unfold(JsonObject o) {
        if (!o.has("unfold")) {
            return null;
        }
        JsonArray a = o.getAsJsonArray("unfold");
        return new float[]{a.get(0).getAsFloat(), a.get(1).getAsFloat(), a.get(2).getAsFloat()};
    }

    private static void collect(ModelPart node, String name, JsonObject spec, Map<String, ModelPart> out) {
        out.put(name, node);
        for (JsonElement e : spec.getAsJsonArray("parts")) {
            JsonObject o = e.getAsJsonObject();
            if (o.get("parent").getAsString().equals(name) && node.hasChild(o.get("name").getAsString())) {
                collect(node.getChild(o.get("name").getAsString()), o.get("name").getAsString(), spec, out);
            }
        }
    }

    /** Builds the model geometry from the JSON spec. */
    public static TexturedModelData build(JsonObject spec) {
        ModelData data = new ModelData();
        Map<String, ModelPartData> nodes = new HashMap<>();
        nodes.put("root", data.getRoot());
        JsonArray arr = spec.getAsJsonArray("parts");
        // parents are always listed before children
        for (JsonElement e : arr) {
            JsonObject o = e.getAsJsonObject();
            ModelPartBuilder b = ModelPartBuilder.create();
            for (JsonElement be : o.getAsJsonArray("boxes")) {
                JsonObject box = be.getAsJsonObject();
                JsonArray uv = box.getAsJsonArray("uv");
                JsonArray from = box.getAsJsonArray("from");
                JsonArray size = box.getAsJsonArray("size");
                b.uv(uv.get(0).getAsInt(), uv.get(1).getAsInt());
                b.mirrored(box.has("mirror") && box.get("mirror").getAsBoolean());
                b.cuboid(from.get(0).getAsFloat(), from.get(1).getAsFloat(), from.get(2).getAsFloat(),
                        size.get(0).getAsFloat(), size.get(1).getAsFloat(), size.get(2).getAsFloat(),
                        new Dilation(box.has("dilate") ? box.get("dilate").getAsFloat() : 0));
            }
            JsonArray piv = o.getAsJsonArray("pivot");
            JsonArray rot = o.has("rot") ? o.getAsJsonArray("rot") : null;
            ModelTransform t = ModelTransform.of(piv.get(0).getAsFloat(), piv.get(1).getAsFloat(), piv.get(2).getAsFloat(),
                    rot == null ? 0 : rot.get(0).getAsFloat(), rot == null ? 0 : rot.get(1).getAsFloat(), rot == null ? 0 : rot.get(2).getAsFloat());
            ModelPartData parent = nodes.get(o.get("parent").getAsString());
            nodes.put(o.get("name").getAsString(), parent.addChild(o.get("name").getAsString(), b, t));
        }
        JsonArray tex = spec.getAsJsonArray("texture");
        return TexturedModelData.of(data, tex.get(0).getAsInt(), tex.get(1).getAsInt());
    }

    @Override
    public ModelPart getPart() {
        return root;
    }

    /** Per-entity smoothed state weights (0..1), eased towards their targets every frame. */
    private float[] blend(UnderdeepCreature e, float age, boolean[] target) {
        float[] b = blends.computeIfAbsent(e, k -> {
            float[] n = new float[N_BLEND + 1];
            n[N_BLEND] = age;
            for (int i = 0; i < N_BLEND; i++) {
                n[i] = target[i] ? 1 : 0;
            }
            return n;
        });
        float dt = MathHelper.clamp(age - b[N_BLEND], 0, 5);
        b[N_BLEND] = age;
        float k = 1 - (float) Math.pow(0.82, dt); // ~0.18 per tick: about a quarter second to settle
        for (int i = 0; i < N_BLEND; i++) {
            b[i] += ((target[i] ? 1 : 0) - b[i]) * k;
        }
        return b;
    }

    @Override
    public void setAngles(UnderdeepCreature e, float limbAngle, float limbDistance, float age, float headYaw, float headPitch) {
        root.traverse().forEach(p -> {
            p.resetTransform();
            p.xScale = p.yScale = p.zScale = 1;
        });
        byte state = e.state();
        boolean swimming = e.isTouchingWater();
        boolean airborne = !e.isOnGround() && !swimming;
        boolean flyer = gait.equals("none");
        boolean[] target = new boolean[N_BLEND];
        target[B_SLEEP] = state == UnderdeepCreature.SLEEP || e.isInSittingPose();
        target[B_EAT] = state == UnderdeepCreature.EAT || state == UnderdeepCreature.DRINK;
        target[B_ALERT] = state == UnderdeepCreature.ALERT;
        target[B_WARN] = state == UnderdeepCreature.WARN;
        target[B_ATTACK] = state == UnderdeepCreature.ATTACK || e.isAttacking();
        target[B_FLY] = airborne && (flyer || e.hasNoGravity() || !e.isOnGround() && e.getVelocity().y > -0.6);
        target[B_SWIM] = swimming;
        float[] b = blend(e, age, target);
        float sleep = b[B_SLEEP], eat = b[B_EAT], alert = Math.max(b[B_ALERT], b[B_WARN]), warn = b[B_WARN], attack = b[B_ATTACK];
        float fly = b[B_FLY], swim = b[B_SWIM];
        float awake = 1 - sleep;

        float seed = (e.getId() * 0.6180339f) % 1f * 100f;
        float amp = Math.min(1.0f, limbDistance) * awake;
        boolean many = gait.equals("hexa") || gait.equals("crab");
        float speed = switch (gait) {
            case "biped" -> 0.55f;
            case "hexa", "crab" -> 1.25f;
            default -> 0.66f;
        };
        float breathe = MathHelper.sin(age * 0.08f + seed) * (0.2f + 0.15f * sleep);
        float idle = (1 - amp) * awake;

        if (!legacy && !many && !flyer && !gait.equals("fish") && !gait.equals("serpent")) {
            root.pivotY += legLength * 0.62f * sleep;
        } else if (legacy) {
            root.pivotY += legLength * 0.7f * sleep;
        }
        if (state == UnderdeepCreature.PLAY) {
            root.pivotY -= Math.abs(MathHelper.sin(age * 0.6f)) * 2.0f;
        }
        if (flyer) {
            root.pivotY += MathHelper.sin(age * 0.12f + seed) * 0.8f * (1 - sleep);
        }
        for (Part pt : parts) {
            ModelPart p = pt.p;
            float s = pt.side == 0 ? 1 : -1;
            float cyc = limbAngle * speed + pt.phase * MathHelper.PI;
            switch (pt.role) {
                case "body" -> {
                    p.pivotY += breathe;
                    p.pitch -= (0.12f + MathHelper.sin(age * 0.5f) * 0.04f) * warn * (gait.equals("quad") ? 1 : 0);
                    if (gait.equals("fish") || gait.equals("serpent")) {
                        p.yaw += MathHelper.sin(age * 0.3f + limbAngle * 0.4f) * 0.08f * (0.4f + amp);
                    }
                    if (gait.equals("biped")) {
                        p.pivotY += Math.abs(MathHelper.cos(cyc)) * 0.6f * amp; // bob with each step
                    }
                }
                case "head" -> {
                    p.yaw += MathHelper.clamp(headYaw, -60, 60) * MathHelper.RADIANS_PER_DEGREE * 0.75f * awake;
                    p.pitch += headPitch * MathHelper.RADIANS_PER_DEGREE * 0.55f * awake;
                    p.yaw += MathHelper.sin(age * 0.031f + seed) * 0.12f * idle;
                    p.pitch += MathHelper.sin(age * 0.023f + seed * 2) * 0.05f * idle;
                    p.pitch += (0.65f + MathHelper.sin(age * 0.6f) * 0.1f) * eat + 0.3f * sleep - 0.3f * alert;
                    p.yaw += 0.35f * sleep;
                    if (e.isBaby()) {
                        p.xScale = p.yScale = p.zScale = 1.35f;
                    }
                }
                case "neck" -> p.pitch += 0.5f * eat - 0.22f * alert + 0.25f * sleep;
                case "jaw" -> {
                    float chew = Math.max(0, MathHelper.sin(age * 0.9f)) * 0.25f * eat;
                    float gape = (0.35f + MathHelper.sin(age * 0.8f) * 0.25f) * Math.max(attack, warn);
                    float pant = amp > 0.6f && gait.equals("quad") ? Math.max(0, MathHelper.sin(age * 0.7f)) * 0.08f : 0;
                    if (pt.side != 0 || p.yaw != 0) { // paired mandibles / pincers open sideways
                        p.yaw += s * (chew + gape) * 0.8f;
                    } else {
                        p.pitch += chew + gape + pant;
                    }
                }
                case "ear" -> {
                    float twitch = MathHelper.sin(age * 0.05f + seed * 1.3f + pt.side) > 0.96f ? MathHelper.sin(age * 2.2f) * 0.25f : 0;
                    p.roll += s * (twitch * awake + 0.35f * sleep - 0.15f * alert);
                    p.pitch += -0.25f * alert + 0.4f * warn + 0.3f * sleep;
                }
                case "leg_upper", "leg", "arm" -> {
                    float swing = MathHelper.cos(cyc) * amp;
                    if (pt.role.equals("arm")) {
                        p.pitch += swing * 0.35f - (0.9f + MathHelper.sin(age * 0.7f) * 0.35f) * attack;
                    } else if (many) {
                        p.yaw += swing * 0.45f * s;
                        p.roll -= s * Math.max(0, MathHelper.sin(cyc)) * 0.3f * amp;
                        p.roll += s * 0.35f * sleep; // splay flat when resting
                    } else if (flyer) {
                        p.pitch += 0.5f * fly;
                    } else {
                        float scale = gait.equals("biped") ? 0.75f : 0.62f;
                        p.pitch += swing * scale * (1 - swim * 0.4f);
                        p.pitch += MathHelper.cos(age * 0.4f + pt.phase * MathHelper.PI) * 0.45f * swim;
                        if (legacy) {
                            p.pitch += (pt.index == 0 ? 1.4f : -1.4f) * sleep;
                        } else if (gait.equals("biped")) {
                            p.pitch -= 0.9f * sleep;
                        } else {
                            p.pitch += (pt.index == 0 ? -1.25f : 1.25f) * sleep; // fold under the body
                        }
                    }
                }
                case "leg_lower" -> {
                    float lift = Math.max(0, MathHelper.sin(cyc)) * amp;
                    if (many) {
                        p.roll += s * lift * 0.25f;
                    } else if (gait.equals("biped")) {
                        p.pitch += lift * 0.9f + 1.6f * sleep;
                    } else {
                        p.pitch += lift * 0.8f + (pt.index == 0 ? 2.3f : -2.3f) * sleep;
                    }
                }
                case "foot" -> p.pitch -= Math.max(0, MathHelper.sin(limbAngle * speed + pt.side * MathHelper.PI)) * 0.4f * amp;
                case "tail" -> {
                    float k = pt.chain + 1;
                    float wave = MathHelper.sin(age * 0.11f + seed - k * 0.6f);
                    p.yaw += wave * (0.1f + 0.05f * k) * awake + MathHelper.cos(limbAngle * speed - k * 0.5f) * 0.15f * amp;
                    p.pitch -= 0.12f * amp * (pt.chain == 0 ? 1 : 0);
                    p.yaw += 0.45f * sleep * (pt.chain == 0 ? 1 : 0.4f);
                    p.pitch -= 0.25f * warn * (pt.chain == 0 ? 1 : 0);
                    p.yaw += MathHelper.sin(age * 1.2f) * 0.2f * warn;
                    if (state == UnderdeepCreature.PLAY) {
                        p.yaw += MathHelper.sin(age * 0.9f) * 0.35f;
                    }
                }
                case "segment" -> {
                    float k = pt.chain;
                    float f = gait.equals("serpent") ? 0.28f : 0.35f;
                    p.yaw += MathHelper.sin(age * f + limbAngle * 0.35f + seed - k * 0.8f) * (0.14f + 0.28f * Math.max(amp, swim * 0.5f));
                }
                case "tentacle" -> {
                    float k = pt.chain + 1;
                    p.pitch += MathHelper.sin(age * 0.09f + pt.index * 0.9f - k * 0.7f) * 0.14f * k;
                    p.roll += MathHelper.cos(age * 0.07f + pt.index * 1.3f - k * 0.5f) * 0.1f * k;
                }
                case "wing", "wing_outer" -> {
                    boolean outer = pt.role.equals("wing_outer");
                    boolean insect = flyer && !legacy && (gait.equals("none"));
                    float rate = insect ? 2.4f : 0.9f;
                    float flap = MathHelper.sin(age * rate - (outer ? 0.7f : 0)) * (insect ? 0.55f : 0.8f);
                    float active = flyer ? Math.max(fly, 1 - sleep) : fly;
                    if (pt.unfold != null) { // folded at rest; opens as the creature takes off
                        p.pitch += pt.unfold[0] * active;
                        p.yaw += pt.unfold[1] * active;
                        p.roll += pt.unfold[2] * active;
                    }
                    if (outer) {
                        p.roll += s * flap * 0.6f * active;
                    } else {
                        p.roll += s * (flap + 0.1f) * active;
                        if (!flyer) {
                            p.roll += s * 0.12f * (1 - active) * (MathHelper.sin(age * 0.05f + seed) > 0.97f ? 1 : 0); // settle the wings
                        }
                    }
                    if (legacy && !flyer && active < 0.5f) {
                        p.roll += s * (1.05f + 0.2f * sleep);
                    }
                }
                case "fin", "fin_outer" -> {
                    boolean outer = pt.role.equals("fin_outer");
                    float k = outer ? 0.7f : 0;
                    p.roll += s * MathHelper.sin(age * 0.16f + pt.phase - k) * (outer ? 0.35f : 0.28f) * (0.5f + 0.5f * Math.max(swim, amp));
                }
                case "fluke" -> p.pitch += MathHelper.sin(age * 0.25f + limbAngle * 0.3f) * 0.3f;
                case "tailfin" -> p.yaw += MathHelper.sin(age * (swim > 0.5f ? 0.55f : 0.9f)) * 0.45f;
                case "antenna" -> {
                    p.pitch += MathHelper.sin(age * 0.3f + pt.side * 1.7f + seed) * 0.12f - 0.2f * alert;
                    p.yaw += MathHelper.cos(age * 0.23f + pt.side + seed) * 0.1f;
                }
                case "crest" -> p.pitch -= 0.35f * Math.max(warn, alert) * (legacy ? 1 : 0.4f);
                case "float" -> {
                    p.pivotY += MathHelper.sin(age * 0.1f + pt.index) * 0.8f;
                    p.pitch += MathHelper.sin(age * 0.15f + pt.index * 0.8f) * 0.15f;
                }
                default -> {
                }
            }
        }
    }
}
