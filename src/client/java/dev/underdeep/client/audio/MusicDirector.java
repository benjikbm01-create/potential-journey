/**
 * Stage 11 continuous soundtrack (client only). Decides a music context every half second, by priority
 * victory > boss > combat > dungeon > settlement > home > travel > ecosystem > fallback, with hysteresis so brief
 * changes never cause a switch; picks a track from the context's pool avoiding recent history; and crossfades between
 * tracks on context changes and at track ends. Vanilla music is suppressed in Underdeep worlds (MusicTrackerMixin).
 * Settings: config/underdeep-client.properties (music.enabled, music.volume, music.gaps) and the client command
 * {@code /underdeep_music}. Tracks are streamed OGG files declared in sounds.json (generated by tools/music/compose.py).
 */
public final class MusicDirector {
    private static final Map<String, List<String>> POOLS = new HashMap<>();
    private static final Map<String, String> TITLES = new HashMap<>();
    private static final Deque<String> HISTORY = new ArrayDeque<>();
    private static final Random RNG = Random.create();

    // settings
    public static boolean enabled = true;
    public static float volume = 1.0f;
    public static boolean gaps = false;

    // state
    static String serverContext = "";
    private static Track current, fading;
    private static String context = "", candidate = "";
    private static int candidateTicks, gapTicks, combatTicks, victoryTicks, tick;
    private static String lastBossEvent = "none";

    private MusicDirector() {
    }

    public static void init() {
        loadTracks();
        loadConfig();
        ClientPlayNetworking.registerGlobalReceiver(MusicContext.Payload.ID, (p, ctx) -> ctx.client().execute(() -> serverContext = p.context()));
        ClientTickEvents.END_CLIENT_TICK.register(MusicDirector::tick);
        ClientPlayConnectionEvents.DISCONNECT.register((h, c) -> c.execute(MusicDirector::reset));
        ClientCommandRegistrationCallback.EVENT.register((d, reg) -> d.register(ClientCommandManager.literal("underdeep_music")
                .executes(c -> status(c.getSource()::sendFeedback))
                .then(ClientCommandManager.literal("on").executes(c -> set(c.getSource()::sendFeedback, () -> enabled = true)))
                .then(ClientCommandManager.literal("off").executes(c -> set(c.getSource()::sendFeedback, () -> enabled = false)))
                .then(ClientCommandManager.literal("gaps").executes(c -> set(c.getSource()::sendFeedback, () -> gaps = true)))
                .then(ClientCommandManager.literal("continuous").executes(c -> set(c.getSource()::sendFeedback, () -> gaps = false)))
                .then(ClientCommandManager.literal("next").executes(c -> {
                    next(2.5f);
                    return status(c.getSource()::sendFeedback);
                }))
                .then(ClientCommandManager.literal("volume").then(ClientCommandManager.argument("percent",
                        com.mojang.brigadier.arguments.IntegerArgumentType.integer(0, 200)).executes(c -> set(c.getSource()::sendFeedback,
                        () -> volume = com.mojang.brigadier.arguments.IntegerArgumentType.getInteger(c, "percent") / 100f))))));
    }

    /** True while the director owns music (Underdeep world, enabled): vanilla's MusicTracker stays silent. */
    public static boolean suppressVanilla() {
        MinecraftClient mc = MinecraftClient.getInstance();
        return enabled && mc.world != null && inUnderdeep(mc);
    }

    // ------------------------------------------------------------------------------------------ context

    private static boolean inUnderdeep(MinecraftClient mc) {
        return mc.player != null && mc.world.getBiome(mc.player.getBlockPos()).getKey().map(k -> k.getValue().getNamespace().equals(Underdeep.MOD_ID))
                .orElse(false);
    }

    /** The highest-priority context that applies now (before hysteresis). */
    static String detect(MinecraftClient mc) {
        ClientPlayerEntity p = mc.player;
        String bossEvent = BossRenderers.audioEvent;
        if (!bossEvent.equals(lastBossEvent)) {
            lastBossEvent = bossEvent;
            if (bossEvent.equals("victory")) {
                victoryTicks = 20 * 45;
            }
        }
        if (victoryTicks > 0) {
            return "victory";
        }
        if (bossEvent.equals("prepare") || bossEvent.equals("activate") || bossEvent.equals("phase")) {
            return "boss:" + BossRenderers.audioBoss;
        }
        if (inCombat(mc, p)) {
            combatTicks = 20 * 9; // linger: a short lull in a fight does not drop the combat music
        }
        if (combatTicks > 0) {
            return "combat";
        }
        String ex = ExploreClient.CONTEXT;
        if (ex != null && !ex.equals("none") && !ex.isEmpty()) {
            return "dungeon:" + ex;
        }
        if (serverContext.startsWith("settlement:")) {
            return serverContext;
        }
        if (serverContext.equals("home")) {
            return "home";
        }
        if (p.hasVehicle()) {
            return "travel";
        }
        String biome = mc.world.getBiome(p.getBlockPos()).getKey().map(k -> k.getValue().getPath()).orElse("");
        return "eco:" + biome.replace("_", "");
    }

    private static boolean inCombat(MinecraftClient mc, ClientPlayerEntity p) {
        if (p.isSpectator() || p.isCreative()) {
            return false;
        }
        Box box = p.getBoundingBox().expand(14, 6, 14);
        for (Entity e : mc.world.getOtherEntities(p, box)) {
            if (e instanceof HostileEntity h && h.isAlive() && (h.isAttacking() || h.squaredDistanceTo(p) < 25 && p.hurtTime > 0)) {
                return true;
            }
            if (e instanceof UnderdeepCreature c && c.isAlive() && (c.state() == UnderdeepCreature.ATTACK || c.isAttacking())
                    && c.squaredDistanceTo(p) < 12 * 12) {
                return true;
            }
            if (e instanceof MobEntity m && m.getTarget() == p) {
                return true;
            }
        }
        return false;
    }

    /** Track pool for a context; falls back down the priority chain when a context has no tracks of its own. */
    static List<String> pool(String ctx) {
        int i = ctx.indexOf(':');
        String kind = i < 0 ? ctx : ctx.substring(0, i), arg = i < 0 ? "" : ctx.substring(i + 1);
        List<String> out = switch (kind) {
            case "victory" -> POOLS.get("victory");
            case "boss" -> List.of("boss_" + arg);
            case "combat" -> POOLS.get("combat");
            case "dungeon" -> switch (arg) {
                case "ruin", "landmark" -> List.of("ruins_a", "ruins_b");
                case "secret" -> List.of("dungeon_secret", "dungeon_vault");
                default -> List.of("dungeon_depths", "dungeon_traps", "dungeon_vault");
            };
            case "settlement" -> List.of("civ_" + arg);
            case "home" -> POOLS.get("home");
            case "travel" -> POOLS.get("travel");
            case "eco" -> List.of(arg + "_a", arg + "_b");
            default -> POOLS.get("home");
        };
        List<String> known = new ArrayList<>();
        for (String s : out == null ? List.<String>of() : out) {
            if (TITLES.containsKey(s)) {
                known.add(s);
            }
        }
        return known.isEmpty() ? POOLS.getOrDefault("home", List.of()) : known;
    }

    private static int priority(String ctx) {
        return switch (ctx.contains(":") ? ctx.substring(0, ctx.indexOf(':')) : ctx) {
            case "victory" -> 9;
            case "boss" -> 8;
            case "combat" -> 6;
            case "dungeon" -> 5;
            case "settlement" -> 4;
            case "home" -> 3;
            case "travel" -> 2;
            case "eco" -> 1;
            default -> 0;
        };
    }

    /** Ticks a new context must persist before the music follows it (hysteresis). */
    private static int settleTicks(String ctx, String from) {
        int p = priority(ctx);
        if (p >= 8) {
            return 0;
        }
        if (p == 6) {
            return 10;
        }
        if (priority(from) == 6) {
            return 40; // after combat, settle back gently
        }
        return p == 1 && priority(from) == 1 ? 20 * 8 : 20 * 4;
    }

    // ------------------------------------------------------------------------------------------ playback

    private static void tick(MinecraftClient mc) {
        tick++;
        if (victoryTicks > 0) {
            victoryTicks--;
        }
        if (combatTicks > 0) {
            combatTicks--;
        }
        if (mc.world == null || mc.player == null || !enabled || !inUnderdeep(mc)) {
            if (current != null) {
                current.fadeOut(2.0f);
                fading = current;
                current = null;
                context = "";
            }
            return;
        }
        if (tick % 10 != 0) {
            maintain(mc);
            return;
        }
        String now = detect(mc);
        if (!now.equals(candidate)) {
            candidate = now;
            candidateTicks = 0;
        } else {
            candidateTicks += 10;
        }
        if (!candidate.equals(context) && candidateTicks >= settleTicks(candidate, context)) {
            boolean samePool = pool(candidate).equals(pool(context)) && current != null;
            String old = context;
            context = candidate;
            if (!samePool) {
                gapTicks = 0;
                float fade = priority(context) >= 6 || priority(old) >= 8 ? 1.5f : 4.0f;
                next(fade);
            }
        }
        maintain(mc);
    }

    private static void maintain(MinecraftClient mc) {
        mc.getMusicTracker().stop(); // vanilla music never plays over ours (also suppressed by the mixin)
        if (current != null && (current.isDone() || !mc.getSoundManager().isPlaying(current)) && current.started) {
            current = null;
            if (gaps && priority(context) < 6) {
                gapTicks = 20 * (40 + RNG.nextInt(90)); // vanilla-style silence between tracks
            }
        }
        if (current == null && !context.isEmpty()) {
            if (gapTicks > 0) {
                gapTicks--;
                return;
            }
            next(2.0f);
        }
        if (current != null && current.remaining() < 4.0f && !current.isFadingOut() && priority(context) < 8 && !gaps) {
            next(4.0f); // crossfade into the following track before this one ends (continuous playback)
        }
    }

    /** Starts the next track for the current context, crossfading the previous one out over {@code fade} seconds. */
    static void next(float fade) {
        MinecraftClient mc = MinecraftClient.getInstance();
        List<String> pool = pool(context);
        if (pool.isEmpty()) {
            return;
        }
        String pick = choose(pool);
        if (current != null) {
            current.fadeOut(fade);
            fading = current;
        }
        current = new Track(pick, TITLES.get(pick), fade);
        HISTORY.addFirst(pick);
        while (HISTORY.size() > 6) {
            HISTORY.removeLast();
        }
        mc.getSoundManager().play(current);
        Underdeep.LOGGER.info("[music] {} -> {} ({})", context, pick, TITLES.get(pick));
    }

    /** Weighted choice avoiding recent history (a fresh track whenever the pool allows it). */
    private static String choose(List<String> pool) {
        List<String> fresh = new ArrayList<>();
        for (String s : pool) {
            int idx = new ArrayList<>(HISTORY).indexOf(s);
            if (idx < 0) {
                fresh.add(s);
                fresh.add(s); // never-recent tracks weigh double
            } else if (idx >= Math.min(2, pool.size() - 1)) {
                fresh.add(s);
            }
        }
        List<String> from = fresh.isEmpty() ? pool : fresh;
        return from.get(RNG.nextInt(from.size()));
    }

    private static void reset() {
        if (current != null) {
            MinecraftClient.getInstance().getSoundManager().stop(current);
        }
        if (fading != null) {
            MinecraftClient.getInstance().getSoundManager().stop(fading);
        }
        current = fading = null;
        context = candidate = serverContext = "";
        victoryTicks = combatTicks = gapTicks = 0;
        lastBossEvent = BossRenderers.audioEvent = "none";
    }

    /** A streamed music track whose volume eases in and out (crossfades). */
    static final class Track extends MovingSoundInstance {
        final String id;
        final String title;
        private float level, target = 1, rate;
        private boolean out;
        boolean started;
        private int ticks;
        private final float seconds;

        Track(String id, String title, float fadeIn) {
            super(SoundEvent.of(Identifier.of(Underdeep.MOD_ID, "music." + id)), SoundCategory.MUSIC, SoundInstance.createRandom());
            this.id = id;
            this.title = title;
            this.repeat = false;
            this.relative = true;
            this.attenuationType = AttenuationType.NONE;
            this.rate = 1f / Math.max(1, fadeIn * 20);
            this.volume = 0.0001f;
            Float s = SECONDS.get(id);
            this.seconds = s == null ? 120 : s;
        }

        void fadeOut(float secs) {
            out = true;
            target = 0;
            rate = 1f / Math.max(1, secs * 20);
        }

        boolean isFadingOut() {
            return out;
        }

        float remaining() {
            return seconds - ticks / 20f;
        }

        @Override
        public boolean shouldAlwaysPlay() {
            return true;
        }

        @Override
        public void tick() {
            started = true;
            ticks++;
            level += Math.signum(target - level) * Math.min(Math.abs(target - level), rate);
            volume = Math.max(0.0001f, level * volume());
            if (out && level <= 0.001f) {
                setDone();
            }
        }

        private static float volume() {
            return MusicDirector.volume;
        }
    }

    // ------------------------------------------------------------------------------------------ data and settings

    private static final Map<String, Float> SECONDS = new HashMap<>();

    private static void loadTracks() {
        try (InputStream in = MusicDirector.class.getResourceAsStream("/assets/underdeep/music_tracks.json")) {
            if (in == null) {
                Underdeep.LOGGER.warn("[music] no track table; music disabled");
                return;
            }
            for (JsonElement e : JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonArray()) {
                var o = e.getAsJsonObject();
                String id = o.get("id").getAsString();
                POOLS.computeIfAbsent(o.get("context").getAsString(), k -> new ArrayList<>()).add(id);
                TITLES.put(id, o.get("title").getAsString());
                SECONDS.put(id, o.get("seconds").getAsFloat());
            }
        } catch (Exception ex) {
            Underdeep.LOGGER.warn("[music] bad track table: {}", ex.toString());
        }
    }

    private static Path configPath() {
        return FabricLoader.getInstance().getConfigDir().resolve("underdeep-client.properties");
    }

    private static void loadConfig() {
        Properties pr = new Properties();
        try (Reader r = Files.newBufferedReader(configPath())) {
            pr.load(r);
        } catch (Exception ignored) {
            // first run: defaults
        }
        enabled = Boolean.parseBoolean(pr.getProperty("music.enabled", "true"));
        gaps = Boolean.parseBoolean(pr.getProperty("music.gaps", "false"));
        try {
            volume = Math.max(0, Math.min(2, Float.parseFloat(pr.getProperty("music.volume", "1.0"))));
        } catch (NumberFormatException e) {
            volume = 1;
        }
        saveConfig();
    }

    private static void saveConfig() {
        Properties pr = new Properties();
        pr.setProperty("music.enabled", Boolean.toString(enabled));
        pr.setProperty("music.gaps", Boolean.toString(gaps));
        pr.setProperty("music.volume", String.format(Locale.ROOT, "%.2f", volume));
        try (Writer w = Files.newBufferedWriter(configPath())) {
            pr.store(w, "Underdeep client settings. music.gaps=true restores vanilla-style silences between tracks; "
                    + "music.volume multiplies the Music slider (0.0-2.0).");
        } catch (Exception e) {
            Underdeep.LOGGER.warn("[music] could not save settings: {}", e.toString());
        }
    }

    private static int set(java.util.function.Consumer<Text> out, Runnable change) {
        change.run();
        saveConfig();
        if (!enabled) {
            reset();
        }
        return status(out);
    }

    private static int status(java.util.function.Consumer<Text> out) {
        out.accept(Text.translatable("message.underdeep.music.status", Text.translatable(enabled ? "options.on" : "options.off"),
                Math.round(volume * 100), Text.translatable(gaps ? "message.underdeep.music.gaps" : "message.underdeep.music.continuous"),
                current == null ? "-" : current.title));
        return 1;
    }
}
